func TestExist(t *testing.T) {
	examples := []struct {
		board  [][]byte
		word   string
		answer bool
	}{
		{[][]byte{
			{'A', 'B', 'C', 'E'},
			{'S', 'F', 'C', 'S'},
			{'A', 'B', 'C', 'B'}}, "ABCB", true},
		{[][]byte{{'A','B','C','E'},{'S','F','C','S'},{'A','D','E','E'}},"ABCCED",true},
		{[][]byte{
			{'A','B','C','E'},
			{'S','F','C','S'},
			{'A','D','E','E'}},"SEE",true},
	}

	for _, e := range examples {
		if result := exist(e.board, e.word); result != e.answer {
			t.Fatalf("result:%v is wrong,example:%v", result, e)
		}
	}
}

